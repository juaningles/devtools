<#
.SYNOPSIS
  Generate cmd.exe shims and PowerShell functions from shell/aliases.sh.

.DESCRIPTION
  Reads every line of shell/aliases.sh, then of the overlay's shell/*.sh
  (docs/OVERLAY.md), that ends in "#win" and emits:
    bin-win/gen/<name>.cmd          one shim per alias (for cmd.exe)
    shell/aliases.generated.ps1     one function per alias (dot-sourced by profile.ps1)

  Two source shapes are recognised:
    alias name='command words'   #win    -> args appended at the end
    name() { cmd "$@" more; }    #win    -> "$@" marks where args go

  Run via install.cmd, install.ps1, sync.ps1, or directly.
#>
[CmdletBinding()]
param(
  [string]$Root
)
$ErrorActionPreference = 'Stop'
if (-not $Root) { $Root = Split-Path -Parent (Split-Path -Parent $MyInvocation.MyCommand.Path) }

$aliasesFile = Join-Path $Root 'shell\aliases.sh'
$genDir      = Join-Path $Root 'bin-win\gen'
$psOut       = Join-Path $Root 'shell\aliases.generated.ps1'

if (-not (Test-Path $aliasesFile)) { throw "not found: $aliasesFile" }
$overlay = if ($env:DEVTOOLS_OVERLAY) { $env:DEVTOOLS_OVERLAY } else { Join-Path $Root 'overlay' }
$sources = @($aliasesFile)
if (Test-Path (Join-Path $overlay 'shell')) {
  $sources += Get-ChildItem (Join-Path $overlay 'shell') -Filter *.sh | Sort-Object Name | ForEach-Object FullName
}
New-Item -ItemType Directory -Force -Path $genDir | Out-Null
Get-ChildItem $genDir -Filter *.cmd | Remove-Item -Force

$reAlias = "^\s*alias\s+([A-Za-z0-9_-]+)='([^']*)'\s*#win\s*$"
$reFunc  = '^\s*([A-Za-z0-9_-]+)\(\)\s*\{\s*(.*?);\s*\}\s*#win\s*$'

$ps = New-Object System.Text.StringBuilder
[void]$ps.AppendLine('# GENERATED by tools/gen-shims.ps1 from shell/aliases.sh and the overlay - do not edit.')
[void]$ps.AppendLine("# $(Get-Date -Format s)")
[void]$ps.AppendLine('')

$count = 0
foreach ($line in ($sources | ForEach-Object { Get-Content $_ })) {
  $name = $null
  if ($line -match $reAlias) {
    $name = $Matches[1]; $cmdBody = "$($Matches[2]) %*"; $psBody = "$($Matches[2]) @args"
  } elseif ($line -match $reFunc) {
    $name = $Matches[1]; $body = $Matches[2]
    if ($body -notmatch '"\$@"') { Write-Warning "skipping $name - function marked #win has no `"`$@`""; continue }
    $cmdBody = $body -replace '"\$@"', '%*'
    $psBody  = $body -replace '"\$@"', '@args'
  } else { continue }

  if ($cmdBody -match '[|$`~]') { Write-Warning "skipping $name - body uses bash-only syntax: $cmdBody"; continue }

  # cmd shim: echo the expanded command (matches the behaviour of the old k*.cmd files), then run it
  $shim = "@echo $cmdBody`r`n@$cmdBody`r`n"
  [IO.File]::WriteAllText((Join-Path $genDir "$name.cmd"), $shim, [Text.Encoding]::ASCII)

  # PowerShell: quote tokens containing commas, otherwise 'pods,jobs' becomes an array and is split into two args
  $psBody = ($psBody -split ' ' | ForEach-Object { if ($_ -match ',') { "'$_'" } else { $_ } }) -join ' '
  # a hyphenated name like 'pacr-login' is a legal function name
  [void]$ps.AppendLine("function $name { $psBody }")
  $count++
}

[IO.File]::WriteAllText($psOut, $ps.ToString(), (New-Object Text.UTF8Encoding $false))
Write-Host "gen-shims: $count aliases -> $genDir\*.cmd and $psOut"
